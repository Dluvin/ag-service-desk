const ES: Record<MessageKey, string> = { ...ES_UI, ...REST_ES };
const TABLES: Record<Locale, Record<MessageKey, string>> = { en: EN, es: ES };

export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  let text = TABLES[locale][key] ?? EN[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function statusLabel(locale: Locale, status: string) {
  const key = `status.${status}` as MessageKey;
  return key in EN ? t(locale, key) : status;
}

export function priorityLabel(locale: Locale, priority: string) {
  const key = `priority.${priority}` as MessageKey;
  return key in EN ? t(locale, key) : priority;
}

export function roleMessageKey(role: string): MessageKey {
  if (role === "ADMIN") return "role.ADMIN";
  if (role === "MANAGER") return "role.MANAGER";
  if (role === "CLERICAL") return "role.CLERICAL";
  if (role === "TECHNICIAN") return "role.TECHNICIAN";
  return "role.FARMER";
}
